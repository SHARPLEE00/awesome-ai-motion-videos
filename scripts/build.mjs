#!/usr/bin/env node
// Builds README.md, README.zh-CN.md and prompts/<id>.md from data/videos.json.
// Every entry links to the creator's own post; nothing is re-hosted.
//
//   node scripts/build.mjs          (fails on an entry that breaks the rules below)
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const videos = JSON.parse(readFileSync(new URL('data/videos.json', root), 'utf8'))
const meta = JSON.parse(readFileSync(new URL('data/collection.json', root), 'utf8'))
const REPO = meta.repo
const utm = (medium) => `utm_source=github&utm_medium=${medium}&utm_campaign=${meta.campaign}`
const lookbk = (path, medium = 'readme') => `https://lookbk.dev${path}${path.includes('?') ? '&' : '?'}${utm(medium)}`

const CATS = [
  { id: 'motion', en: 'Motion graphics & launch videos', zh: '动效与发布片', more: '/skills/series/launch-films' },
  { id: '3d', en: '3D scenes & worlds', zh: '3D 场景与世界', more: '/skills/series/motion-heroes' },
  { id: 'interactive', en: 'Games & interactive', zh: '游戏与互动', more: '/skills' },
  { id: 'comparison', en: 'Model comparisons', zh: '模型对比', more: '/skills' },
]

// Rules every entry must pass.
const ids = new Set()
for (const v of videos) {
  const where = `entry ${v.id}`
  if (!/^\d{15,20}$/.test(v.id)) throw new Error(`${where}: bad status id`)
  if (ids.has(v.id)) throw new Error(`${where}: duplicate`)
  ids.add(v.id)
  if (v.url !== `https://x.com/${v.handle}/status/${v.id}`) throw new Error(`${where}: url does not match handle and id`)
  if (!CATS.some((c) => c.id === v.category)) throw new Error(`${where}: unknown category ${v.category}`)
  if (!v.title || !v.titleZh) throw new Error(`${where}: needs title and titleZh`)
  if (v.prompt && !v.promptUrl) throw new Error(`${where}: a prompt needs the URL where the creator published it`)
}
videos.sort((a, b) => (b.date || '').localeCompare(a.date || '') || b.id.localeCompare(a.id))

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const dur = (v) => (v.duration ? `${Math.round(v.duration)}s` : '')
const models = (v) => (v.models?.length ? v.models.join(' · ') : '')
const count = (c) => videos.filter((v) => v.category === c).length
const withPrompt = videos.filter((v) => v.prompt).length
const accounts = new Set(videos.map((v) => v.handle.toLowerCase())).size
const modelCounts = Object.entries(
  videos.flatMap((v) => v.models ?? []).reduce((m, x) => ((m[x] = (m[x] || 0) + 1), m), {}),
).sort((a, b) => b[1] - a[1])

function card(v, zh) {
  const title = zh ? v.titleZh : v.title
  const img = v.thumb ? `<a href="${v.url}"><img src="${v.thumb}" alt="${esc(title)}" width="100%"></a><br>` : ''
  const promptLink = v.prompt ? ` · <a href="prompts/${v.id}.md">${zh ? '提示词' : 'Prompt'}</a>` : ''
  const facts = [dur(v), models(v)].filter(Boolean).join(' · ')
  return `<td width="33%" valign="top">${img}<b><a href="${v.url}">${esc(title)}</a></b><br><sub><a href="https://x.com/${v.handle}">@${v.handle}</a>${facts ? ' · ' + esc(facts) : ''}${promptLink}</sub></td>`
}

function grid(list, zh) {
  const rows = []
  for (let i = 0; i < list.length; i += 3) {
    const r = list.slice(i, i + 3).map((v) => card(v, zh))
    while (r.length < 3) r.push('<td width="33%"></td>')
    rows.push(`<tr>\n${r.join('\n')}\n</tr>`)
  }
  return `<table>\n${rows.join('\n')}\n</table>`
}

function promptsTable(zh) {
  const list = videos.filter((v) => v.prompt)
  if (!list.length) return ''
  const head = zh ? '| 作品 | 作者 | 模型 |\n| --- | --- | --- |' : '| Piece | Creator | Model |\n| --- | --- | --- |'
  return `${head}\n${list.map((v) => `| [${esc(zh ? v.titleZh : v.title)}](prompts/${v.id}.md) | [@${v.handle}](${v.url}) | ${esc(models(v))} |`).join('\n')}`
}

function readme(zh) {
  const t = (en, cn) => (zh ? cn : en)
  const toc = CATS.filter((c) => count(c.id))
    .map((c) => `[${t(c.en, c.zh)} (${count(c.id)})](#${t(c.en, c.zh).toLowerCase().replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-')})`)
    .join(' · ')
  const sections = CATS.filter((c) => count(c.id))
    .map(
      (c) => `## ${t(c.en, c.zh)}

${grid(videos.filter((v) => v.category === c.id), zh)}

<sub>${t('Make this kind of thing with your own agent:', '想让你的 agent 也做出这种效果：')} <a href="${lookbk(c.more, `readme-${c.id}`)}">${t('skills on Lookbk →', '看 Lookbk 上的技能 →')}</a></sub>`,
    )
    .join('\n\n')
  return `<!-- ${t('Generated by scripts/build.mjs from data/videos.json. Edit those, not this file.', '由 scripts/build.mjs 根据 data/videos.json 生成，请改数据，不要直接改这里。')} -->
<div align="center">

<a href="${lookbk('/skills', 'banner')}"><img src="media/cover.png" alt="${t(meta.title, meta.titleZh)}" width="100%"></a>

# ${t(meta.title, meta.titleZh)}

${t(meta.tagline, meta.taglineZh)}

**${videos.length}** ${t('pieces', '个作品')} · **${accounts}** ${t('creators', '位创作者')} · **${withPrompt}** ${t('with the exact prompt', '附原始提示词')} · ${t('updated', '更新于')} ${meta.updated}

${t('English', '[English](README.md)')} · ${t('[简体中文](README.zh-CN.md)', '简体中文')}

**[${t('▶ Make videos like these with agent skills on Lookbk', '▶ 用 Lookbk 上的技能，让你的 agent 也做出这样的视频')}](${lookbk('/skills', 'hero')})**

</div>

${t(
  'Since Claude Opus 5.5 shipped on 22 September 2026, people have been asking coding models for motion graphics, launch films, 3D worlds and games, and getting them back as code: three.js, canvas, SVG, Remotion or HyperFrames, rendered to video. This list collects the best of what they posted on X, newest first, with credit to every creator and the exact prompt wherever the creator published one. New models get their own entries as they ship.',
  '自从 2026 年 9 月 22 日 Claude Opus 5.5 发布，大家开始让写代码的模型直接做动效、发布片、3D 世界和小游戏，产出的都是代码：three.js、canvas、SVG、Remotion 或 HyperFrames，再渲染成视频。这里收集了大家发在 X 上的优秀作品，新的在前，每条都署名原作者；作者公开了提示词的，原样附上。之后有新模型发布，也会继续收录。',
)}

${toc}

${t('Models in this list', '收录的模型')}: ${modelCounts.map(([m, n]) => `${m} (${n})`).join(' · ')}

${sections}

## ${t('Prompts you can reuse', '可以直接用的提示词')}

${t('Creators published these prompts with their work. Each page quotes the prompt as posted and links to where it was posted.', '这些提示词是作者随作品公开的。每页都原样引用，并链接到作者发布的位置。')}

${promptsTable(zh)}

## ${t('Add a piece', '投稿')}

${t(
  `Found or made something that belongs here? [Open a submission](https://github.com/${REPO}/issues/new?template=submit.yml) with the post link. We add pieces made mostly by an AI model, credited to the creator and linked to their post. See [CONTRIBUTING.md](CONTRIBUTING.md).`,
  `看到或做了适合收录的作品？[提交一条](https://github.com/${REPO}/issues/new?template=submit.yml)，附上原帖链接。我们收录主要由 AI 模型完成的作品，署名作者并链接原帖。详见 [CONTRIBUTING.md](CONTRIBUTING.md)。`,
)}

## ${t('Credits and rights', '署名与版权')}

${t(
  'Every video, prompt and quoted post belongs to its creator. This repository links to the original posts and shows the thumbnails X itself serves; it does not copy or re-host anyone’s video. The MIT license covers only this repository’s own scripts and structure. Model credits follow what each creator said. To correct a credit or remove an entry, see [MEDIA-RIGHTS.md](MEDIA-RIGHTS.md).',
  '所有视频、提示词和引用的帖子文字都归原作者所有。本仓库只链接原帖，缩略图直接引用 X 自己的图片地址，不复制、不转存任何人的视频。MIT 许可只覆盖本仓库自己的脚本和结构。使用的模型以作者自述为准。需要更正署名或删除条目，见 [MEDIA-RIGHTS.md](MEDIA-RIGHTS.md)。',
)}

${t('Not affiliated with Anthropic, Moonshot AI, OpenAI or Google. Maintained by', '与 Anthropic、Moonshot AI、OpenAI、Google 均无关联。维护者：')} [Lookbk](${lookbk('/', 'footer')}) · ${t('agent skills for video, slides, images and web pages', '做视频、幻灯片、图片和网页的 agent 技能')}.
`
}

function promptPage(v) {
  const quote = v.prompt.split('\n').map((l) => `> ${l}`).join('\n')
  return `# ${v.title}

${v.thumb ? `[![${v.title}](${v.thumb})](${v.url})\n\n` : ''}**[▶ ${'Watch the original post'}](${v.url})** · [@${v.handle}](https://x.com/${v.handle})${v.date ? ` · ${v.date}` : ''}${dur(v) ? ` · ${dur(v)}` : ''}${models(v) ? ` · ${models(v)}` : ''}

## Prompt

As published by the creator [here](${v.promptUrl}):

${quote}

${v.notes ? `## Notes\n\n${v.notes}\n\n` : ''}## Original post

${v.text.split('\n').map((l) => `> ${l}`).join('\n')}

---

The video, prompt and post text belong to [@${v.handle}](https://x.com/${v.handle}). Quoted here with credit and a link; see [media rights](../MEDIA-RIGHTS.md).

[Make videos like this with your own agent →](${lookbk('/skills', 'prompt-page')})
`
}

writeFileSync(new URL('README.md', root), readme(false))
writeFileSync(new URL('README.zh-CN.md', root), readme(true))
rmSync(new URL('prompts/', root), { recursive: true, force: true })
mkdirSync(new URL('prompts/', root))
for (const v of videos.filter((x) => x.prompt)) writeFileSync(new URL(`prompts/${v.id}.md`, root), promptPage(v))
console.log(`${videos.length} entries, ${accounts} creators, ${withPrompt} prompts; ${CATS.map((c) => `${c.id} ${count(c.id)}`).join(', ')}`)
